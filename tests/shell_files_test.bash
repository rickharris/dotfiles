#!/bin/bash
# Tests for scripts/shell_files.sh, against fixture files in a temp directory
# and against this repo's own scripts.
set -u
repo=$(cd "$(dirname "$0")/.." && pwd -P)
list=$repo/scripts/shell_files.sh

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

failed=0

# expect <group> <file> <yes|no>: whether the file is listed in the group.
expect() {
  local group=$1 file=$2 want=$3 got=no
  if [[ -n $(/bin/bash "$list" "$group" "$file") ]]; then
    got=yes
  fi
  if [[ $got == "$want" ]]; then
    echo "ok   - $group $want: ${file#"$tmp"/}"
  else
    echo "FAIL - $group $want: ${file#"$tmp"/} (got $got)"
    failed=1
  fi
}

# fixture <name> <first line>
fixture() {
  printf '%s\necho hi\n' "$2" >"$tmp/$1"
}

fixture plain.sh 'echo hi'
fixture plain.bash 'echo hi'
fixture plain.zsh 'echo hi'
fixture bin-sh '#!/bin/sh'
fixture bin-bash '#!/bin/bash -e'
fixture env-bash '#!/usr/bin/env bash'
fixture bin-zsh '#!/bin/zsh'
fixture env-zsh '#!/usr/bin/env zsh'
fixture modeline '# vim:ft=zsh'
fixture compdef '#compdef dot'
fixture python '#!/usr/bin/env python3'
fixture fish '#!/usr/bin/env fish'
fixture text 'just some text'
: >"$tmp/empty"
mkdir -p "$tmp/home"
fixture home/dot-p10k.zsh '# Generated by Powerlevel10k'

for f in plain.sh plain.bash bin-sh bin-bash env-bash; do
  expect sh "$tmp/$f" yes
  expect zsh "$tmp/$f" no
done
for f in plain.zsh bin-zsh env-zsh modeline compdef; do
  expect zsh "$tmp/$f" yes
  expect sh "$tmp/$f" no
done
for f in python fish text empty home/dot-p10k.zsh missing; do
  expect sh "$tmp/$f" no
  expect zsh "$tmp/$f" no
done

# With no files it lists the repo's own, relative to its top.
sh_files=$(/bin/bash "$list" sh)
zsh_files=$(/bin/bash "$list" zsh)
for f in home/dot-local/bin/dot layers/personal/install scripts/shell_files.sh; do
  if grep -qx "$f" <<<"$sh_files"; then
    echo "ok   - repo sh: $f"
  else
    echo "FAIL - repo sh: $f is missing"
    failed=1
  fi
done
for f in home/dot-zshrc home/dot-local/share/zsh/site-functions/_dot; do
  if grep -qx "$f" <<<"$zsh_files"; then
    echo "ok   - repo zsh: $f"
  else
    echo "FAIL - repo zsh: $f is missing"
    failed=1
  fi
done
if grep -qx home/dot-p10k.zsh <<<"$zsh_files"; then
  echo "FAIL - repo zsh: generated home/dot-p10k.zsh is listed"
  failed=1
else
  echo "ok   - repo zsh: generated home/dot-p10k.zsh is left out"
fi

if /bin/bash "$list" bash >/dev/null 2>&1; then
  echo "FAIL - an unknown group is refused"
  failed=1
else
  echo "ok   - an unknown group is refused"
fi

exit "$failed"
